/**
 * Ensure sidebars.ts covers every API category folder and types autogeneration.
 */
import {readFileSync, readdirSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sidebarsSrc = readFileSync(join(root, 'sidebars.ts'), 'utf8');
const apiRefSrc = readFileSync(join(root, 'src/data/api-reference.ts'), 'utf8');

function parseApiRefCounts(src) {
  const counts = {};
  const re = /to: '\/docs\/reference\/api\/([^']+)', count: (\d+)/g;
  let m;
  while ((m = re.exec(src))) {
    counts[m[1]] = Number(m[2]);
  }
  return counts;
}

const refCounts = parseApiRefCounts(apiRefSrc);

const apiRoot = join(root, 'docs/reference/api');
const diskCategories = readdirSync(apiRoot, {withFileTypes: true})
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const missingFromSidebar = diskCategories.filter(
  (cat) => !sidebarsSrc.includes(`'${cat}'`) && !sidebarsSrc.includes(`"${cat}"`),
);

const typesRoot = join(root, 'docs/reference/types');
const typeSlugs = readdirSync(typesRoot)
  .filter((f) => f.endsWith('.mdx') && f !== 'index.mdx')
  .map((f) => f.replace(/\.mdx$/, ''));

const typesAutogenerated =
  sidebarsSrc.includes("dirName: 'reference/types'") ||
  sidebarsSrc.includes('dirName: "reference/types"');

const missingTypes = typesAutogenerated
  ? []
  : typeSlugs.filter((slug) => !sidebarsSrc.includes(`reference/types/${slug}`));

const countMismatches = [];
for (const cat of diskCategories) {
  const dir = join(apiRoot, cat);
  const exportPages = readdirSync(dir).filter(
    (f) => f.endsWith('.mdx') && f !== 'index.mdx',
  ).length;
  const expected = refCounts[cat];
  if (expected !== undefined && exportPages !== expected) {
    countMismatches.push(`${cat}: disk=${exportPages} api-reference.ts=${expected}`);
  }
}

const errors = [];
if (missingFromSidebar.length) {
  errors.push(`API categories missing from sidebars.ts: ${missingFromSidebar.join(', ')}`);
}
if (missingTypes.length) {
  errors.push(`Type pages missing from sidebars.ts: ${missingTypes.join(', ')}`);
}
if (countMismatches.length) {
  errors.push(`Export count mismatches:\n  ${countMismatches.join('\n  ')}`);
}

if (errors.length) {
  console.error('check:sidebar-coverage FAILED:\n' + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

console.log(
  `OK: ${diskCategories.length} API categories in sidebar, ${typeSlugs.length} type pages ${typesAutogenerated ? '(autogenerated)' : '(listed)'}.`,
);
